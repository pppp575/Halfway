// Extends src/data/schedule.json (the daily city pairs) and rewrites supabase/puzzles.sql.
// Existing days are never changed, so past puzzles stay the same.
// Usage: npm run schedule            (730 days from LAUNCH_DATE)
//        npm run schedule -- --days=1095
import { readFile, writeFile } from 'node:fs/promises';
import { CITIES } from '../src/data/cities.js';
import { LAUNCH_DATE, ROUNDS } from '../src/lib/constants.js';
import { isoAddDays } from '../src/lib/dates.js';
import { generatedPairs, roundData } from '../src/lib/puzzles.js';

const arg = process.argv.find((a) => a.startsWith('--days='));
const DAYS = arg ? Number(arg.split('=')[1]) : 730;
const scheduleUrl = new URL('../src/data/schedule.json', import.meta.url);
const sqlUrl = new URL('../supabase/puzzles.sql', import.meta.url);

let schedule = { start: LAUNCH_DATE, cities: CITIES.length, days: [] };
try {
  const existing = JSON.parse(await readFile(scheduleUrl, 'utf8'));
  if (existing.start === LAUNCH_DATE) schedule = existing;
  else console.warn(`LAUNCH_DATE changed (${existing.start} -> ${LAUNCH_DATE}); building a new schedule.`);
} catch {
  /* first run */
}

const before = schedule.days.length;
for (let i = schedule.days.length; i < DAYS; i++) {
  schedule.days.push(generatedPairs(isoAddDays(LAUNCH_DATE, i)).flat());
}
schedule.cities = CITIES.length;

// One day per line keeps git diffs readable.
const json = `{"start":"${schedule.start}","cities":${schedule.cities},"days":[\n${schedule.days.map((d) => JSON.stringify(d)).join(',\n')}\n]}\n`;
await writeFile(scheduleUrl, json);

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const n = (x) => Number(x.toFixed(6));
const rows = [];
schedule.days.forEach((row, i) => {
  const day = isoAddDays(schedule.start, i);
  for (let r = 0; r < ROUNDS; r++) {
    const R = roundData([row[r * 2], row[r * 2 + 1]]);
    rows.push(
      `(${q(day)},${r + 1},${q(R.A.n)},${q(R.B.n)},${n(R.a[0])},${n(R.a[1])},${n(R.b[0])},${n(R.b[1])},${n(R.m[0])},${n(R.m[1])},${n(R.dist)})`,
    );
  }
});
const chunks = [];
for (let i = 0; i < rows.length; i += 500) {
  chunks.push(
    'insert into public.puzzles (day, round, a_name, b_name, a_lon, a_lat, b_lon, b_lat, mid_lon, mid_lat, dist_km) values\n' +
      rows.slice(i, i + 500).join(',\n') +
      '\non conflict (day, round) do update set a_name = excluded.a_name, b_name = excluded.b_name, a_lon = excluded.a_lon,' +
      ' a_lat = excluded.a_lat, b_lon = excluded.b_lon, b_lat = excluded.b_lat, mid_lon = excluded.mid_lon, mid_lat = excluded.mid_lat,' +
      ' dist_km = excluded.dist_km;',
  );
}
const last = isoAddDays(schedule.start, schedule.days.length - 1);
await writeFile(
  sqlUrl,
  `-- Generated by \`npm run schedule\`. Do not edit by hand. Safe to run more than once.\n-- Puzzles from ${schedule.start} to ${last} (${schedule.days.length} days).\n\n${chunks.join('\n\n')}\n`,
);
console.log(`Schedule: ${before} -> ${schedule.days.length} days (until ${last}). Wrote supabase/puzzles.sql.`);
